/**
 * Versioned, forward-only Postgres migrations, tracked in schema_migrations.
 * Each migration runs in its own transaction under an advisory lock so two
 * server instances starting together cannot both apply it. Never edit a
 * migration that has shipped; add a new one.
 *
 * Migration 1 recreates the layout the old supabase_schema.sql produced, so a
 * database that already has those tables passes through it untouched and is
 * then upgraded by 2..4 exactly like a fresh one.
 */
