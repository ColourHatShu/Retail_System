export const LATEST_SCHEMA_VERSION = migrations[migrations.length - 1].version;

const ADVISORY_LOCK_KEY = 7_303_291; // arbitrary constant shared by all server instances

export async function runMigrations(pool: Pool): Promise<void> {
  const client = await pool.connect();
  try {
    await client.query(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        version    INTEGER PRIMARY KEY,
        name       TEXT NOT NULL,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )
    `);

    await client.query('SELECT pg_advisory_lock($1)', [ADVISORY_LOCK_KEY]);
    try {
      const applied = new Set(
        (await client.query<{ version: number }>('SELECT version FROM schema_migrations')).rows.map((r) =>
          Number(r.version),
        ),
      );

      for (const m of migrations) {
        if (applied.has(m.version)) continue;
        await client.query('BEGIN');
        try {
          await client.query(m.sql);
          await client.query('INSERT INTO schema_migrations (version, name) VALUES ($1, $2)', [m.version, m.name]);
          await client.query('COMMIT');
        } catch (err) {
          await client.query('ROLLBACK');
          throw new Error(`Migration ${m.version} (${m.name}) failed: ${(err as Error).message}`);
        }
        if (process.env.NODE_ENV !== 'test') {
          console.log(`[db] applied migration ${m.version}: ${m.name}`);
        }
      }
    } finally {
      await client.query('SELECT pg_advisory_unlock($1)', [ADVISORY_LOCK_KEY]);
    }
  } finally {
    client.release();
  }
}
