-- 6. ATOMIC POS CHECKOUT RPC FUNCTION
CREATE OR REPLACE FUNCTION public.process_pos_checkout(
    p_items JSONB,
    p_subtotal NUMERIC,
    p_tax_rate NUMERIC,
    p_tax_amount NUMERIC,
    p_discount NUMERIC,
    p_total NUMERIC,
    p_payment_method TEXT,
    p_amount_paid NUMERIC,
    p_change_due NUMERIC,
    p_customer_name TEXT,
    p_customer_phone TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_receipt_number TEXT;
    v_sale_id BIGINT;
    v_item JSONB;
    v_prod RECORD;
    v_qty INT;
    v_unit_price NUMERIC;
    v_total_price NUMERIC;
    v_qty_before INT;
    v_qty_after INT;
    v_date_str TEXT;
    v_rand_suffix TEXT;
    v_res_items JSONB := '[]'::JSONB;
BEGIN
    -- Generate receipt number e.g. REC-20260909-XXXX
    v_date_str := to_char(timezone('utc', now()), 'YYYYMMDD');
    v_rand_suffix := upper(substr(md5(random()::text), 1, 4));
    v_receipt_number := 'REC-' || v_date_str || '-' || v_rand_suffix;

    -- 1. Insert into sales
    INSERT INTO public.sales (
        receipt_number, subtotal, tax_rate, tax_amount, discount, total,
        payment_method, amount_paid, change_due, customer_name, customer_phone
    ) VALUES (
        v_receipt_number, p_subtotal, p_tax_rate, p_tax_amount, p_discount, p_total,
        p_payment_method, p_amount_paid, p_change_due, COALESCE(p_customer_name, 'Walk-in Customer'), p_customer_phone
    ) RETURNING id INTO v_sale_id;

    -- 2. Process each item
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_qty := (v_item->>'quantity')::INT;
        
        -- Lock product row
        SELECT * INTO v_prod FROM public.products 
        WHERE id = (v_item->>'product_id')::BIGINT 
           OR barcode = (v_item->>'barcode')::TEXT
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Product not found: %', COALESCE(v_item->>'barcode', v_item->>'product_id');
        END IF;

        IF v_prod.stock_quantity < v_qty THEN
            RAISE EXCEPTION 'Insufficient stock for "%". Available: %, Requested: %', v_prod.name, v_prod.stock_quantity, v_qty;
        END IF;

        v_unit_price := COALESCE((v_item->>'unit_price')::NUMERIC, v_prod.price);
        v_total_price := round(v_unit_price * v_qty, 2);
        v_qty_before := v_prod.stock_quantity;
        v_qty_after := v_qty_before - v_qty;

        -- Update stock
        UPDATE public.products 
        SET stock_quantity = v_qty_after, updated_at = timezone('utc', now())
        WHERE id = v_prod.id;

        -- Insert sale item
        INSERT INTO public.sale_items (
            sale_id, product_id, product_name, barcode, quantity, unit_price, total_price
        ) VALUES (
            v_sale_id, v_prod.id, v_prod.name, v_prod.barcode, v_qty, v_unit_price, v_total_price
        );

        -- Record movement history
        INSERT INTO public.stock_movements (
            product_id, type, quantity_change, quantity_before, quantity_after,
            reference_id, reason, customer_name, customer_phone, payment_method, sale_id
        ) VALUES (
            v_prod.id, 'SALE', -v_qty, v_qty_before, v_qty_after,
            v_receipt_number, 'POS Sale #' || v_receipt_number,
            COALESCE(p_customer_name, 'Walk-in Customer'), p_customer_phone, p_payment_method, v_sale_id
        );

        v_res_items := v_res_items || jsonb_build_object(
            'product_id', v_prod.id,
            'name', v_prod.name,
            'barcode', v_prod.barcode,
            'quantity', v_qty,
            'unit_price', v_unit_price,
            'total_price', v_total_price,
            'unit', v_prod.unit
        );
    END LOOP;

    RETURN jsonb_build_object(
        'id', v_sale_id,
        'receipt_number', v_receipt_number,
        'subtotal', p_subtotal,
        'tax_rate', p_tax_rate,
        'tax_amount', p_tax_amount,
        'discount', p_discount,
        'total', p_total,
        'payment_method', p_payment_method,
        'amount_paid', p_amount_paid,
        'change_due', p_change_due,
        'customer_name', COALESCE(p_customer_name, 'Walk-in Customer'),
        'created_at', timezone('utc', now()),
        'items', v_res_items
    );
END;
$$;

